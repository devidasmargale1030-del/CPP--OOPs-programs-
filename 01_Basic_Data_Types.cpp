// Program 1: Basic Data Types
// Scenario: Store student roll number, grade, and fee amount.

#include <iostream>
using namespace std;

int main() {
    int roll = 101;
    char grade = 'A';
    float fee = 12500.50;

    cout << "Roll No: " << roll << endl;
    cout << "Grade: " << grade << endl;
    cout << "Fee: " << fee << endl;

    return 0;
}

/*
Expected Output:
Roll No: 101
Grade: A
Fee: 12500.5
*/
